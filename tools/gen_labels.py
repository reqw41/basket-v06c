#!/usr/bin/env python3
"""cfg/labels.json -> src/v06/labels.inc and per-unit includes (sjasm equ).

  python3 tools/gen_labels.py           # write the includes
  python3 tools/gen_labels.py --check   # fail if any include is stale

An assembly unit (a file the builder assembles, with its `include`d files)
that DEFINES a labels.json name as a label cannot see that name as an equ:
sjasm would reject the redefinition as soon as the code moves. Such a unit
includes `labels_<unit>.inc`, which leaves its own labels out;
tools/link_labels.py then writes the unit's real addresses back into
cfg/labels.json. Every other unit includes labels.inc with all names.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import os
SRC = ROOT / "cfg/labels.json"
SRCDIR = Path(os.environ.get("BASKET_SRCDIR", ROOT / "src/v06"))
OUT = SRCDIR / "labels.inc"
RX_INC = re.compile(r'^\s*#?include\s+"([^"]+)"', re.I)
RX_LAB = re.compile(r"^([A-Za-z_]\w*):")


def includes(path: Path) -> list[str]:
    return [m.group(1) for line in path.read_text(errors="replace").splitlines()
            if (m := RX_INC.match(line)) and m.group(1).endswith(".asm")]


def units() -> dict[str, list[Path]]:
    """Top-level unit stem -> its files (itself first)."""
    files = sorted(SRCDIR.glob("*.asm"))
    included = {inc for f in files for inc in includes(f)}
    out = {}
    for f in files:
        if f.name in included:
            continue
        todo, seen = [f], []
        while todo:
            x = todo.pop(0)
            seen.append(x)
            todo += [SRCDIR / i for i in includes(x)]
        out[f.stem] = seen
    return out


def owners(labels: dict) -> dict[str, str]:
    """label -> unit stem that defines it as a label."""
    own = {}
    for unit, files in units().items():
        for f in files:
            for line in f.read_text(errors="replace").splitlines():
                m = RX_LAB.match(line)
                if m and m.group(1) in labels and not re.search(r"\bequ\b", line, re.I):
                    if own.get(m.group(1), unit) != unit:
                        raise SystemExit(f"{m.group(1)} defined in {own[m.group(1)]} and {unit}")
                    own[m.group(1)] = unit
    return own


def render(labels: dict, skip=frozenset(), unit: str | None = None) -> str:
    lines = ["; GENERATED by tools/gen_labels.py from cfg/labels.json — do not edit.",
             "; Game (MSX image, relocated D-block, work RAM) and cross-module addresses.",
             "; Modules use these names, never the numbers (tools/test_labels.py)."]
    if unit:
        lines.append(f"; Unit {unit}.asm: its own labels are left out (tools/link_labels.py).")
    lines.append("")
    for name, e in sorted(labels.items(), key=lambda kv: int(kv[1]["addr"], 16)):
        if name not in skip:
            lines.append(f"{name:<27} equ     0x{e['addr']}  ; {e['kind']}: {e['note']}")
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    labels = json.loads(SRC.read_text())["labels"]
    # tools/build_i8080_rom.py: game-code labels at their i8080 addresses.
    if os.environ.get("BASKET_LABEL_OVERRIDES"):
        over = json.loads(Path(os.environ["BASKET_LABEL_OVERRIDES"]).read_text())
        labels = {n: dict(e, addr=over.get(n, e["addr"])) for n, e in labels.items()}
    own = owners(labels)
    out = {OUT: render(labels)}
    for unit in sorted(set(own.values())):
        mine = frozenset(n for n, u in own.items() if u == unit)
        out[SRCDIR / f"labels_{unit}.inc"] = render(labels, mine, unit)
    return out


def main() -> int:
    outs = outputs()
    stale_files = sorted(p for p in SRCDIR.glob("labels_*.inc") if p not in outs)
    if "--check" in sys.argv:
        bad = [p.name for p, t in outs.items() if not p.exists() or p.read_text() != t]
        bad += [p.name + " (no owner)" for p in stale_files]
        if bad:
            print("stale includes: " + ", ".join(bad) + " — run tools/gen_labels.py")
            return 1
        print(f"labels includes in sync ({len(outs)} files)")
        return 0
    for p in stale_files:
        p.unlink()
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    print(f"{len(outs)} include files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
