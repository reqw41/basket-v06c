#!/usr/bin/env python3
"""Disassemble the Executive main payload and check an exact round-trip.

The payload is deliberately treated as one address space: reachable Z80
instructions are emitted with labels and everything else is emitted as DB.
That keeps graphics/tables opaque until their consumers are understood.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPIRITS = Path(os.environ.get("SPIRITS_V06C", str(Path.home() / "projects/spirits-v06c")))
sys.path.insert(0, str(SPIRITS / "tools" / "vendor"))
from z80dis import decode  # noqa: E402

BASE = 0x84D0
ENTRY = BASE
PAYLOAD = ROOT / "ref/msx/executive/executive.block2.bin"
DEFAULT_OUT = ROOT / "disasm/msx/orig/game.asm"


def reachable(mem: bytearray, end: int) -> dict[int, object]:
    code: dict[int, object] = {}
    pending = [ENTRY]
    while pending:
        pc = pending.pop()
        if pc in code or not BASE <= pc < end:
            continue
        while BASE <= pc < end and pc not in code:
            try:
                ins = decode(mem[pc:], pc)
            except Exception:
                break
            if pc + ins.length > end:
                break
            code[pc] = ins
            for target in ins.targets:
                if BASE <= target < BASE + len(mem):
                    pending.append(target)
            if ins.flow in ("jump", "ret", "dyn", "halt") and not ins.fmt.startswith("ret "):
                break
            pc += ins.length
    return code


def labels_for(code: dict[int, object]) -> dict[int, str]:
    labels = {ENTRY: "GAME_ENTRY"}
    for ins in code.values():
        for target in ins.targets:
            if target in code:
                labels.setdefault(target, f"L_{target:04X}")
    return labels


def emit(payload: bytes, code: dict[int, object]) -> str:
    mem = bytearray(0x10000)
    mem[BASE : BASE + len(payload)] = payload
    labels = labels_for(code)
    lines = [
        "; Fernando Martin Basket Master Executive, block 2",
        "; Generated by tools/disasm_exec.py; data gaps remain DB until audited.",
        f"; source: executive.block2.bin, {len(payload)} bytes, {BASE:04X}..{BASE + len(payload) - 1:04X}",
        f"        org 0x{BASE:04X}",
        "",
    ]
    pc = BASE
    end = BASE + len(payload)
    while pc < end:
        if pc in labels:
            lines.append(f"{labels[pc]}:")
        ins = code.get(pc)
        if ins is not None:
            operand = labels.get(ins.operand) if ins.operand in labels else None
            lines.append(f"        {ins.text(operand)}")
            pc += ins.length
            continue
        gap_start = pc
        gap = bytearray()
        while pc < end and pc not in code and pc not in labels and len(gap) < 16:
            gap.append(mem[pc])
            pc += 1
        values = ",".join(f"0x{x:02X}" for x in gap)
        lines.append(f"        db {values} ; data {gap_start:04X}..{pc - 1:04X}")
    lines.append("")
    return "\n".join(lines)


def assemble(source: Path, output: Path) -> tuple[bool, str]:
    candidates = []
    for sjasm in (
        SPIRITS / "tools/bin/sjasm",
        Path.home() / "projects/kvalley-v06c/tools/bin/sjasm",
    ):
        if sjasm.exists():
            candidates.append([str(sjasm), str(source), str(output)])
    for name in ("zasm", "sjasm"):
        found = __import__("shutil").which(name)
        if found:
            candidates.append([found, str(source), str(output)])
    if not candidates:
        return False, "assembler unavailable"
    for command in candidates:
        output.unlink(missing_ok=True)
        result = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
        if result.returncode == 0 and output.exists():
            actual = output.read_bytes()
            expected = PAYLOAD.read_bytes()
            if actual == expected:
                return True, f"round-trip green ({len(actual)} bytes)"
            return False, f"assembler output differs ({len(actual)} vs {len(expected)} bytes)"
    return False, (result.stderr or result.stdout or "assembler failed").strip()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--no-assemble", action="store_true")
    args = parser.parse_args()
    payload = PAYLOAD.read_bytes()
    mem = bytearray(0x10000)
    mem[BASE : BASE + len(payload)] = payload
    code = reachable(mem, BASE + len(payload))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(emit(payload, code))
    print(f"{args.output}: {len(payload)} bytes, {len(code)} reachable instructions")
    if args.no_assemble:
        return 0
    ok, message = assemble(args.output, ROOT / "build/exec-block2.bin")
    print(message)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
